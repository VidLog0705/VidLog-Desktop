namespace VidLog.Desktop.Core.Theme;

/// <summary>
/// 暗色主题的色值表（改造清单第 5 批）。
/// </summary>
/// <remarks>
/// <para>
/// <b>这里只有暗色，没有亮色。</b> 亮色的唯一来源是
/// <c>src/VidLog.Desktop.App/Theme.xaml</c> —— 那套值是需求方 32 张设计图里
/// 逐像素量出来的（见该文件头）。把亮色也抄一份进来，就等于多了一个会跟
/// <c>Theme.xaml</c> 各自漂移的副本；本仓刚为这种「同一个数写两份」修过两处
/// （清单 T29 磁盘槽位魔数、T30 许可文案）。所以这张表只回答一个问句：
/// **暗色下这个键改成什么**。
/// </para>
/// <para>
/// ⚠️ <b>键名必须与 <c>Theme.xaml</c> 里的资源键逐字相同，一个不差。</b>
/// 这条由 <c>ThemePaletteTests</c> 钉着（它把 <c>Theme.xaml</c> 解析出来逐个比）：
/// <list type="bullet">
///   <item>少一个键 ⇒ 那个颜色在暗色下**保持亮色值** —— 白底黑字漏在暗色界面上，
///         而这正是 ZoneMinder 那个反面教材的形状（清单第 5 批点名的那一条）；</item>
///   <item>多一个键 ⇒ 静默无效，没有任何东西会喊。</item>
/// </list>
/// 两种都得让测试红。
/// </para>
/// <para>
/// ⚠️ <b>色值不是拍的</b>：每一对「字压在面上」都按 WCAG 相对亮度算过，
/// 算不出标准的就换值 —— 量与结论记在 <c>ThemePaletteTests</c> 的对比度那几条里
/// （它们会跑，改坏了会红）。几处按的是**关系**不是 Tailwind 步进，见各条注释。
/// </para>
/// </remarks>
public static class ThemePalette
{
    /// <summary>
    /// 亮色 → 暗色的改动表。值是 XAML 的颜色字面量
    /// （<c>#RRGGBB</c>；带透明度的写 <c>#AARRGGBB</c>）。
    /// </summary>
    /// <remarks>
    /// 顺序照 <c>Theme.xaml</c> 里那些键出现的顺序排，方便两边对着看。
    /// </remarks>
    public static readonly IReadOnlyDictionary<string, string> Dark =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            // ── 面 ────────────────────────────────────────────────
            // 页面底：亮色是 gray-100（比侧栏浅），暗色取 slate-900。
            ["PageBackground"] = "#0F172A",

            // ⚠️ 这是个 <Color> 资源（不是 Brush），而且**全仓没有一处引用它**
            // （笔刷 `PageBackground` 才是真在用的那个）。留在这儿只为让
            // 「键集必须一一对上」那条检查能成立 —— 见类注释。
            ["PageBackgroundColor"] = "#0F172A",

            // 侧栏：亮色里它比页面底**浅**一档（slate-50 浮在 gray-100 上），
            // 暗色里方向对调 ⇒ 比页底**深**一档（slate-950）。
            // 不这么办的话侧栏与页底同色（对比 1.00:1），边界整条消失，
            // 而「选中项浮在侧栏上」这个效果正是靠这两档差撑着的。
            ["SidebarBackground"] = "#020617",

            ["Surface"] = "#1E293B",

            // 次级区块：亮色 F8FAFC 与页底 F3F4F6 基本同色 ⇒ 暗色也取页底色。
            ["SurfaceMuted"] = "#0F172A",

            // ⚠️ 这一支的**方向必须反过来**：亮色里 slate-100 比卡片**暗**一档
            // （所以它当悬停叠加、当底栏，看着是「压下去」的）；暗色里若还取更暗的，
            // 悬停就变成了「越悬停越黑」，看不见。取比卡片**亮**一档的 slate-700。
            ["SurfaceAlt"] = "#334155",

            ["CardBorder"] = "#334155",

            // 输入框 / 次级按钮的描边。亮色里它比卡片边（slate-200）**深**一档，
            // 暗色里同一条关系 ⇒ **亮**一档（slate-600）。
            ["BorderStrong"] = "#475569",

            // ── 字 ────────────────────────────────────────────────
            ["TextPrimary"] = "#F1F5F9",
            ["TextSecondary"] = "#94A3B8",
            ["TextDisabled"] = "#64748B",

            // ── 强调色（两支，见下） ──────────────────────────────
            // ⚠️ `Accent` 在 Theme.xaml 里**身兼两职**（当底：主按钮、开关轨道；
            // 当前景：文字、图标描边），而暗色下这两个角色要的值是**相反**的：
            //   当底 → 上面压白字，必须留住 blue-600（白字 5.17:1，见 P2 那次裁定）；
            //   当前景 → 压在 slate-800 上，blue-600 只有 2.83:1（连图形要的 3:1 都不到）、
            //            blue-500 也只有 3.98:1（文字不够 4.5）⇒ 必须提到 blue-400。
            // 所以拆成两支：这一支是**前景**（文字/图标/描边），`AccentSolid` 是**底**。
            // ⚠️ 亮色下两支同值（都是 #2563EB）⇒ 亮色的渲染逐像素不变。
            ["Accent"] = "#60A5FA",

            // 见上：当实心底用，白字压上去两套主题都是 5.17:1。
            ["AccentSolid"] = "#2563EB",

            // 选中项底（设置页选中的那一行、日历上「有录像的那天」、配置向导当前那一步）。
            // ⚠️ 2026-10-07 之后它**不再兼进度条轨道**那个角色了（那件事交给
            // `ProgressFill` 与各条轨道自己的键），所以这里只管一件事：
            // 上面压深字要看得清（正文 13.41:1、强调字 5.78:1），
            // 且自己不能跟页面底撞车（1.21:1，见碰撞那条绊线）。
            ["AccentWeak"] = "#172554",

            // 主按钮禁用态。亮色是 blue-500 兑白（看着「褪色」）；暗色的对应做法是
            // 往**深底**那头兑 ⇒ blue-900。
            ["AccentDisabled"] = "#1E3A8A",

            // 禁用态主按钮上那行字的墨色。
            // ⚠️ 原来这一格在模板里**写死 `White`**，暗色下压 `AccentDisabled` 是 10.36:1、
            // **比可用态（5.17:1）还高** —— 禁用反而最显眼。做法不是加 `Opacity`
            // （那会改到亮色），而是**拆一支墨色**：亮色取 `#FFFFFF`（= 原来的值，
            // 亮色一个像素不变），暗色取 `TextDisabled` 那一档 ⇒ 2.18:1，退到可用态之下。
            // 绊线：`ThemePaletteTests.禁用态不许比可用态还显眼`。
            ["PrimaryDisabledInk"] = "#64748B",

            // 进度条的**填充**（向导进度、麦克风电平、容量条、启动窗那条）。
            // ⚠️ 与 `AccentSolid` 分开是为了暗色的轨道：四条进度条的轨道各用各的键
            // （`AccentWeak` / `SurfaceAlt` / `SurfaceMuted` / `BorderStrong`），
            // 暗色下这四块面与 blue-600 的亮度差太小 —— 只有 1.47–3.45:1，
            // 最坏那条（容量条压 `BorderStrong`）等于看不见填充（图形要 3.0）。
            // blue-400 还差一点（容量条 2.98:1）⇒ 用 blue-300（4.20–9.90:1）。
            // 亮色那支与 `AccentSolid` 同值（`#2563EB`）⇒ 亮色一个像素不变。
            ["ProgressFill"] = "#93C5FD",

            // ── 语义色 ────────────────────────────────────────────
            // ⚠️ `Success` / `Danger` 两支**两套主题同值**，是有意的：亮绿/亮红压白字
            // 本来就不达标（2.54:1 / 3.76:1，两套一样），把暗色那支**提亮**只会更糟
            // （emerald-400 压白字 2.0:1）。这两对钉在「明知差一点」那条里。
            ["Success"] = "#10B981",

            // ⚠️ `Warning` 暗色**不是**亮色那个值的对齐：亮色 2026-10-07 已从
            // amber-500 改成 orange-700 `#C2410C`（原来当文字只有 2.15:1、
            // 当描边 2.07:1，两副都不达标）；暗色的 amber-500 压在暗底上
            // 6.81:1、压在暗警示块上 6.79:1，**本来就够**，所以不动。
            // ⇒ 这一支两套主题不同值，是量出来的结论，不是漏改。
            ["Warning"] = "#F59E0B",
            ["Danger"] = "#EF4444",

            // 警示块的底：亮色 amber-50 压深字；暗色取 amber-950（正文 13.30:1）。
            // ⚠️ 「警示字自身」那一对：暗色 6.79:1 ✅；亮色原来是 **2.07:1 不达标**，
            // 2026-10-07 把亮色 `Warning` 压暗到 orange-700 之后是 **4.99:1** ✅。
            // ⚠️ 但**代码里根本没有「琥珀字压琥珀底」这一处**：那两块警示块
            // （`MainWindow` 两处）的字是 `TextPrimary`／`Caption`，琥珀只当描边。
            // 这一对是**假想的**，钉着只是为了「哪天有人真那么写」时有个数。
            ["WarningSurface"] = "#422006",

            // ── 压在画面上的那几层 ────────────────────────────────
            // 预览区深底：亮色 slate-900；暗色再深一档（slate-950），
            // 免得跟页面底（也是 slate-900）糊在一起。
            ["VideoBackground"] = "#020617",

            // 不变：它本来就压在深底上，两套主题都一样。
            ["OverlayPillBackground"] = "#CC1E293B",

            // 不变：投影不参与主题（暗色下投影仍是黑的）—— 见 Theme.xaml 那条注释。
            ["ShadowColor"] = "#000000",

            // ── 交互叠加层（本次从 ControlTemplate 里提出来的） ────
            // ⚠️ Theme.xaml 原来把这三支写成模板内的**字面量**（`#1F000000` 这类），
            // 靠的是「在底色上叠一层半透明黑，对任何底色都成立」这条规律。
            // 那条规律在暗色下**不成立** —— 半透明黑压在深底上等于没压，
            // 悬停/按下**看不见**。所以提成资源，暗色这边换成半透明白。
            ["HoverOverlay"] = "#1FFFFFFF",
            ["HoverOverlaySoft"] = "#0FFFFFFF",
            ["PressedOverlay"] = "#33FFFFFF",
        };

    /// <summary>
    /// Windows 说没说「应用用深色」。
    /// </summary>
    /// <param name="appsUseLightTheme">
    /// 注册表 <c>HKCU\Software\Microsoft\Windows\CurrentVersion\Themes\Personalize\
    /// AppsUseLightTheme</c> 的值：<c>1</c> = 浅色，<c>0</c> = 深色，
    /// <c>null</c> = 这个值不在（更老的系统、或者被组策略删掉了）。
    /// </param>
    /// <remarks>
    /// ⚠️ <b>只有 <c>0</c> 才算深色</b>，别的（<c>null</c>、<c>2</c>、负数）一律当浅色。
    /// 默认值必须是浅色：这套界面是从需求方的亮色设计图量出来的，
    /// 而「读不到系统偏好」不是「用户要深色」。
    /// </remarks>
    public static bool IsDark(int? appsUseLightTheme) => appsUseLightTheme == 0;
}
